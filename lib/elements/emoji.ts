export const EMOJI: EmojiItem[] = EMOJI_GROUPS.flatMap((group) => LIST[group].map(([e, name, keywords]) => ({ e, name, group, ...(keywords ? { keywords } : {}) })));

const byEmoji = new Map(EMOJI.map((x) => [x.e, x]));
/** The list's name of an emoji ("fire"), if it has one. */
export const emojiName = (e: string | undefined) => (e ? byEmoji.get(e)?.name : undefined);

const PICTO = /\p{Extended_Pictographic}|\p{Regional_Indicator}|⃣/u;
/** The whole emoji in `text`, in order (skin tones, families, flags and keycaps stay one piece). */
export function emojisIn(text: string): string[] {
  const seg = typeof Intl !== "undefined" && "Segmenter" in Intl ? new Intl.Segmenter(undefined, { granularity: "grapheme" }) : null;
  const parts = seg ? [...seg.segment(text.trim())].map((s) => s.segment) : [...text.trim()];
  return parts.filter((p) => PICTO.test(p)).map((p) => p.slice(0, 32));
}

/** The first whole emoji in `text`, or null when there's none (the "Any emoji" box). */
export const firstEmoji = (text: string): string | null => emojisIn(text)[0] ?? null;
