export function queryMemes(query?: string, category?: MemeCategory): MemeClipItem[] {
  let list = MEME_CATALOG;
  if (category && category !== "all") {
    list = list.filter((m) => m.category === category);
  }
  if (query && query.trim()) {
    const q = query.trim().toLowerCase();
    const filtered = list.filter((m) => {
      return (
        m.title.toLowerCase().includes(q) ||
        m.dialogue.toLowerCase().includes(q) ||
        m.actorOrShow.toLowerCase().includes(q) ||
        m.tags.some((t) => t.toLowerCase().includes(q))
      );
    });
    // If filtering by subcategory produced 0 results, fall back to searching the entire catalog
    if (filtered.length === 0 && category && category !== "all") {
      return MEME_CATALOG.filter((m) => {
        return (
          m.title.toLowerCase().includes(q) ||
          m.dialogue.toLowerCase().includes(q) ||
          m.actorOrShow.toLowerCase().includes(q) ||
          m.tags.some((t) => t.toLowerCase().includes(q))
        );
      });
    }
    return filtered;
  }
  return list;
}
